CREATE SCHEMA IF NOT EXISTS newsletter;
SET search_path TO newsletter, public;

/*---tables---*/
CREATE TABLE IF NOT EXISTS admins
(
    admin_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_login VARCHAR(80) NOT NULL UNIQUE,
    admin_password_hash VARCHAR(255) NOT NULL,
    admin_name VARCHAR(120) NOT NULL,
    admin_email VARCHAR(254) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100) NOT NULL DEFAULT CURRENT_USER,
    updated_at TIMESTAMPTZ,
    updated_by VARCHAR(100),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    row_version BIGINT NOT NULL DEFAULT 1 CHECK (row_version > 0)
);

CREATE TABLE IF NOT EXISTS newsletters
(
    newsletter_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id BIGINT NOT NULL REFERENCES admins(admin_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100) NOT NULL DEFAULT CURRENT_USER,
    published_at TIMESTAMPTZ,
    title VARCHAR(200) NOT NULL,
    main_info TEXT NOT NULL,
    image_url VARCHAR(2048),
    is_hidden BOOLEAN NOT NULL DEFAULT TRUE,
    published_by VARCHAR(100),
    updated_at TIMESTAMPTZ,
    updated_by VARCHAR(100),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    row_version BIGINT NOT NULL DEFAULT 1 CHECK (row_version > 0),
    CONSTRAINT ck_newsletters_publish_time CHECK
        (is_hidden OR published_at IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS newsletter_delivery_settings
(
    newsletter_id BIGINT PRIMARY KEY REFERENCES newsletters(newsletter_id),
    scheduled_at TIMESTAMPTZ,
    recipient_settings JSONB NOT NULL DEFAULT '{"subscribers": true}'::jsonb,
    reply_to_email VARCHAR(254),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100) NOT NULL DEFAULT CURRENT_USER,
    updated_at TIMESTAMPTZ,
    updated_by VARCHAR(100),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    row_version BIGINT NOT NULL DEFAULT 1 CHECK (row_version > 0)
);

CREATE TABLE IF NOT EXISTS users_copy
(
    user_id BIGINT PRIMARY KEY,
    user_name VARCHAR(50) NOT NULL,
    user_email VARCHAR(254),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100) NOT NULL DEFAULT 'account-events',
    source_updated_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by VARCHAR(100) NOT NULL DEFAULT 'account-events',
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    row_version BIGINT NOT NULL DEFAULT 1 CHECK (row_version > 0)
);

CREATE TABLE IF NOT EXISTS user_comments
(
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users_copy(user_id),
    newsletter_id BIGINT NOT NULL REFERENCES newsletters(newsletter_id),
    parent_comment_id BIGINT REFERENCES user_comments(comment_id),
    comment_text VARCHAR(4000) NOT NULL,
    is_hidden BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100) NOT NULL DEFAULT CURRENT_USER,
    updated_at TIMESTAMPTZ,
    updated_by VARCHAR(100),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    row_version BIGINT NOT NULL DEFAULT 1 CHECK (row_version > 0)
);

CREATE TABLE IF NOT EXISTS subscriptions
(
    subscription_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users_copy(user_id),
    newsletter_id BIGINT NOT NULL REFERENCES newsletters(newsletter_id),
    sub_status VARCHAR(20) NOT NULL DEFAULT 'Active'
        CHECK (sub_status IN ('Active', 'Unsubscribed')),
    consent_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    unsubscribe_token UUID NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    user_email_snapshot VARCHAR(254),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100) NOT NULL DEFAULT CURRENT_USER,
    updated_at TIMESTAMPTZ,
    updated_by VARCHAR(100),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    row_version BIGINT NOT NULL DEFAULT 1 CHECK (row_version > 0),
    CONSTRAINT uq_subscriptions_user_newsletter UNIQUE (user_id, newsletter_id)
);

/*---indexes---*/
CREATE INDEX IF NOT EXISTS ix_newsletters_public_feed
    ON newsletters (published_at DESC) WHERE is_hidden IS FALSE AND is_deleted IS FALSE;

CREATE INDEX IF NOT EXISTS ix_newsletters_admin_history
    ON newsletters (admin_id, created_at DESC);

CREATE INDEX IF NOT EXISTS ix_comments_newsletter_thread
    ON user_comments (newsletter_id, created_at) WHERE is_deleted IS FALSE;

CREATE INDEX IF NOT EXISTS ix_subscriptions_delivery
    ON subscriptions (newsletter_id, user_id) WHERE sub_status = 'Active' AND is_deleted IS FALSE;

COMMENT ON INDEX newsletter.ix_newsletters_public_feed IS
    'Loads visible, active newsletters in reverse publication order for the public feed.';
COMMENT ON INDEX newsletter.ix_newsletters_admin_history IS
    'Loads an admin''s newsletters newest first in the editorial history.';
COMMENT ON INDEX newsletter.ix_comments_newsletter_thread IS
    'Loads non-deleted comments for one newsletter in chronological thread order.';
COMMENT ON INDEX newsletter.ix_subscriptions_delivery IS
    'Finds active subscribers for a newsletter when preparing deliveries.';
