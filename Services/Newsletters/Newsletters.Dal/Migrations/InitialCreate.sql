CREATE TABLE newsletter.admins (
    admin_id bigint GENERATED BY DEFAULT AS IDENTITY,
    admin_login character varying(80) NOT NULL,
    admin_password_hash character varying(255) NOT NULL,
    admin_name character varying(120) NOT NULL,
    admin_email character varying(254) NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    created_by character varying(100) NOT NULL DEFAULT (CURRENT_USER),
    updated_at timestamp with time zone,
    updated_by character varying(100),
    is_deleted boolean NOT NULL DEFAULT FALSE,
    row_version bigint NOT NULL DEFAULT 1,
    CONSTRAINT "PK_admins" PRIMARY KEY (admin_id),
    CONSTRAINT ck_admins_row_version CHECK (row_version > 0)
);

CREATE TABLE newsletter.users_copy (
    user_id bigint NOT NULL,
    user_name character varying(50) NOT NULL,
    user_email character varying(254),
    created_at timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    created_by character varying(100) NOT NULL DEFAULT 'account-events',
    source_updated_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    updated_by character varying(100) NOT NULL DEFAULT 'account-events',
    is_deleted boolean NOT NULL DEFAULT FALSE,
    row_version bigint NOT NULL DEFAULT 1,
    CONSTRAINT "PK_users_copy" PRIMARY KEY (user_id),
    CONSTRAINT ck_users_copy_row_version CHECK (row_version > 0)
);

CREATE TABLE newsletter.newsletters (
    newsletter_id bigint GENERATED BY DEFAULT AS IDENTITY,
    admin_id bigint NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    created_by character varying(100) NOT NULL DEFAULT (CURRENT_USER),
    published_at timestamp with time zone,
    title character varying(200) NOT NULL,
    main_info text NOT NULL,
    image_url character varying(2048),
    is_hidden boolean NOT NULL DEFAULT TRUE,
    published_by character varying(100),
    updated_at timestamp with time zone,
    updated_by character varying(100),
    is_deleted boolean NOT NULL DEFAULT FALSE,
    row_version bigint NOT NULL DEFAULT 1,
    CONSTRAINT "PK_newsletters" PRIMARY KEY (newsletter_id),
    CONSTRAINT ck_newsletters_publish_time CHECK (is_hidden OR published_at IS NOT NULL),
    CONSTRAINT ck_newsletters_row_version CHECK (row_version > 0),
    CONSTRAINT "FK_newsletters_admins_admin_id" FOREIGN KEY (admin_id) REFERENCES newsletter.admins (admin_id) ON DELETE RESTRICT
);

CREATE TABLE newsletter.newsletter_delivery_settings (
    newsletter_id bigint NOT NULL,
    scheduled_at timestamp with time zone,
    recipient_settings jsonb NOT NULL DEFAULT ('{"subscribers": true}'::jsonb),
    reply_to_email character varying(254),
    created_at timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    created_by character varying(100) NOT NULL DEFAULT (CURRENT_USER),
    updated_at timestamp with time zone,
    updated_by character varying(100),
    is_deleted boolean NOT NULL DEFAULT FALSE,
    row_version bigint NOT NULL DEFAULT 1,
    CONSTRAINT "PK_newsletter_delivery_settings" PRIMARY KEY (newsletter_id),
    CONSTRAINT ck_newsletter_delivery_settings_row_version CHECK (row_version > 0),
    CONSTRAINT "FK_newsletter_delivery_settings_newsletters_newsletter_id" FOREIGN KEY (newsletter_id) REFERENCES newsletter.newsletters (newsletter_id) ON DELETE CASCADE
);

CREATE TABLE newsletter.subscriptions (
    subscription_id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    newsletter_id bigint NOT NULL,
    sub_status character varying(20) NOT NULL DEFAULT 'Active',
    consent_at timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    unsubscribe_token uuid NOT NULL DEFAULT (gen_random_uuid()),
    user_email_snapshot character varying(254),
    created_at timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    created_by character varying(100) NOT NULL DEFAULT (CURRENT_USER),
    updated_at timestamp with time zone,
    updated_by character varying(100),
    is_deleted boolean NOT NULL DEFAULT FALSE,
    row_version bigint NOT NULL DEFAULT 1,
    CONSTRAINT "PK_subscriptions" PRIMARY KEY (subscription_id),
    CONSTRAINT ck_subscriptions_row_version CHECK (row_version > 0),
    CONSTRAINT ck_subscriptions_status CHECK (sub_status IN ('Active', 'Unsubscribed')),
    CONSTRAINT "FK_subscriptions_newsletters_newsletter_id" FOREIGN KEY (newsletter_id) REFERENCES newsletter.newsletters (newsletter_id) ON DELETE RESTRICT,
    CONSTRAINT "FK_subscriptions_users_copy_user_id" FOREIGN KEY (user_id) REFERENCES newsletter.users_copy (user_id) ON DELETE RESTRICT
);

CREATE TABLE newsletter.user_comments (
    comment_id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    newsletter_id bigint NOT NULL,
    parent_comment_id bigint,
    comment_text character varying(4000) NOT NULL,
    is_hidden boolean NOT NULL DEFAULT FALSE,
    created_at timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    created_by character varying(100) NOT NULL DEFAULT (CURRENT_USER),
    updated_at timestamp with time zone,
    updated_by character varying(100),
    is_deleted boolean NOT NULL DEFAULT FALSE,
    row_version bigint NOT NULL DEFAULT 1,
    CONSTRAINT "PK_user_comments" PRIMARY KEY (comment_id),
    CONSTRAINT ck_user_comments_row_version CHECK (row_version > 0),
    CONSTRAINT "FK_user_comments_newsletters_newsletter_id" FOREIGN KEY (newsletter_id) REFERENCES newsletter.newsletters (newsletter_id) ON DELETE RESTRICT,
    CONSTRAINT "FK_user_comments_user_comments_parent_comment_id" FOREIGN KEY (parent_comment_id) REFERENCES newsletter.user_comments (comment_id) ON DELETE RESTRICT,
    CONSTRAINT "FK_user_comments_users_copy_user_id" FOREIGN KEY (user_id) REFERENCES newsletter.users_copy (user_id) ON DELETE RESTRICT
);

